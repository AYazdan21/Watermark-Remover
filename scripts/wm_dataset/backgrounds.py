"""Loading and screening for clean background pages used as compositing
targets in the synthetic watermark-segmentation dataset.

Two responsibilities:

1. ``iter_backgrounds`` -- walk a directory of background images (our own
   generated pages, or any real scanned/screenshotted documents someone
   drops in later) and yield them as PIL Images, tolerant of mixed
   formats/sizes/color modes.

2. ``looks_watermarked`` -- a screening filter to run over every background
   BEFORE compositing a synthetic watermark onto it. If a page already has
   a real watermark on it and we stamp a second one on top, the ground-truth
   mask we generate only covers the mark WE added -- the model then sees the
   pre-existing mark as unlabeled "clean" pixels and gets punished for
   correctly flagging it. That silently poisons training with contradictory
   labels. Any background this function flags True should be dropped from
   the compositing pool (or at minimum hand-reviewed), not composited onto.

Detector design -- and why it isn't the obvious "just run YOLO" answer
------------------------------------------------------------------------
This reuses two watermark-detection building blocks already in this repo
(read-only -- nothing here modifies them), combined because neither is
sufficient alone:

- ``watermark_remover.segmenter.detect_watermark_masks``: the project's
  full detection pipeline -- two fine-tuned YOLO11 checkpoints (unioned),
  MobileSAM box-refinement, and a false-positive classifier that rejects
  instances that are "colored UI chrome" (saturated background) or
  "opaque ink" (median alpha too high to be a semi-transparent overlay).
  THIS classifier turned out to matter enormously: calling the raw YOLO
  boxes directly (no SAM/classify) flagged **40/40** of our own clean
  synthetic pages as watermarked (see "measured results" below) -- the raw
  detector fires on ordinary table gridlines, form-field borders and
  colored bars almost everywhere. Running the full pipeline (SAM +
  classify) is what makes this usable at all, at the cost of being much
  slower (SAM box-prompts every YOLO detection; a dense table with 50+
  candidate boxes can take a minute on CPU).
- ``watermark_remover.localizer.localize_watermark``: a fast, model-free
  morphological heuristic (paper estimate at text-scale vs. several
  coarser mark-scale estimates). Kept as a second, OR-ed signal solely
  because it catches a few real watermark instances the segmenter's YOLO
  models miss outright at their confidence floor (see 82/83/84 below) --
  not because it is precise on its own (it isn't; see limits).

Measured results (full run over every file in both sets, this exact
`looks_watermarked` function, logged during development -- not a
cherry-picked subsample):

- dataset/document_originals (16 real watermarked pages): flags **16/16**
  (100% recall). The segmenter alone gets 13/16 -- it misses 3 pages
  (82,83,84) where the watermark is so faint the YOLO detectors don't
  reach their confidence floor at all (top raw score 0.07); the localizer
  catches those (confidence 0.91 on all three). This is the concrete
  reason both signals are kept rather than using the stronger one alone.
- wm_backgrounds (this project's own 40 clean synthetic pages, 8 per
  archetype, generated by gen_persian_docs.py): flags **27/40 (67.5%)** --
  a real, substantial false-positive rate, NOT evenly spread:

      spreadsheet        8/8  (100%)  -- worst case, every sample flagged
      tabular_document   7/8  (87.5%)
      tender_notice      4/8  (50%)
      form_layout        4/8  (50%)
      plain_letter       4/8  (50%)

  This lines up with the mechanism described above: the archetypes with
  dense small-font numeric text in tight grids (spreadsheet, tabular) are
  where SAM-refined instances most often land in an alpha range the
  opaque-ink classifier accepts, and where the localizer's coarse-vs-fine
  morphological bands are most easily confused by a repeating grid. This
  was measured AFTER switching from raw YOLO boxes (which flagged 40/40,
  i.e. was completely useless) to the full SAM+classify pipeline -- a real
  improvement, but nowhere near a solved problem for this document style.
- Runtime, CPU, full pipeline: roughly 1-30s per page for most archetypes,
  60-150s for a dense table/spreadsheet page with 40+ candidate boxes
  (SAM box-prompts every candidate). The 40-page synthetic run above took
  ~14 minutes total on CPU.

Practical implication: this filter is trustworthy for its actual intended
purpose -- screening real-world document images before they enter the
compositing pool, where it got 100% recall on the one labeled real-world
sample available. It is NOT reliable enough to use as an automatic gate on
our own generator's tabular/spreadsheet output specifically -- those
archetypes should be treated as clean by construction (we wrote the
generator, we know it never draws a watermark) rather than re-validated
with this filter. Any True verdict on synthetic pages from those two
archetypes is expected and should not be treated as evidence of an actual
problem; a True verdict on a tender_notice/form_layout/plain_letter page,
or on any real/third-party image, is worth a human glance before dropping
the page from the pool.

Honest limits of this detector (read before trusting it blindly):

- The false-positive classifier's two rejection rules (opaque ink,
  saturated chrome) were designed to separate real semi-transparent marks
  from document/screenshot UI furniture on REAL scanned/screenshotted
  documents. Our synthetic pages are cleanly vector-rendered with crisp
  anti-aliased small text, which lands in an alpha range the classifier
  didn't expect and can accept as "watermark-like". This is a genuine,
  measured gap, not a hypothetical one -- see above.
- The YOLO detectors were fine-tuned on this project's own watermark
  examples (a shield logo mark, a tiled "CONFIDENTIAL"-style stamp, a
  tender-notice mark). They generalize reasonably to similar semi-
  transparent logo/text stamps but are not a general watermark classifier
  -- an unfamiliar watermark style could still slip through undetected.
- The localizer is a heuristic tuned for "a broad, flat, semi-transparent
  region that isn't body text" and CAN false-positive on ordinary page
  furniture with the same coarse-vs-fine structure (heavy color bars,
  thick borders, rule lines) -- see measured results above.
- Both signals only look at pixel statistics / learned appearance. A
  watermark that is extremely faint (alpha near 0, below both detectors'
  floor) or that exactly mimics normal page content (e.g. a large,
  opaque, centered logo that is actually part of a real letterhead) is
  out of scope for either method.
- Running the full segmenter pipeline is slow on CPU (SAM box-prompts
  every YOLO candidate) -- budget roughly 1-90 seconds per image
  depending on how many candidate boxes the page produces; a dense table
  is the slow case.
- This is a screening filter, not a certification. Treat True as "drop or
  review", and treat False as "no evidence found", not "guaranteed clean".
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Iterator, Tuple, Union

import numpy as np
from PIL import Image

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp", ".tif", ".tiff"}

ImageLike = Union[str, "os.PathLike[str]", Image.Image, np.ndarray]


def iter_backgrounds(directory: Union[str, "os.PathLike[str]"]) -> Iterator[Tuple[Path, Image.Image]]:
    """Yields ``(path, image)`` for every readable image file directly
    inside ``directory`` (non-recursive; callers wanting recursion can glob
    themselves and call :func:`_load_image` per path).

    Robust to a mixed bag of files: skips non-image extensions, skips files
    that fail to decode (corrupt/truncated) rather than raising, and always
    hands back an RGB image regardless of the source mode (L, P, RGBA, CMYK,
    etc.) so downstream compositing code never has to special-case modes.
    """
    directory = Path(directory)
    if not directory.is_dir():
        return
    for path in sorted(directory.iterdir()):
        if not path.is_file() or path.suffix.lower() not in IMAGE_EXTS:
            continue
        img = _load_image(path)
        if img is not None:
            yield path, img


def _load_image(path: Union[str, "os.PathLike[str]"]) -> Image.Image | None:
    try:
        with Image.open(path) as im:
            im.load()
            if im.mode != "RGB":
                im = im.convert("RGB")
            return im
    except Exception:
        return None


def _to_rgb_array(img: ImageLike) -> np.ndarray:
    """Normalizes any of {path, PIL.Image, numpy array} into an HxWx3 RGB
    uint8 array, matching the RGB convention used throughout
    watermark_remover (see doc_core.clean_document: ``np.array(image.convert("RGB"))``)."""
    if isinstance(img, np.ndarray):
        arr = img
        if arr.ndim == 2:
            arr = np.stack([arr] * 3, axis=-1)
        elif arr.shape[-1] == 4:
            arr = arr[:, :, :3]
        return np.ascontiguousarray(arr[:, :, :3].astype(np.uint8))
    if isinstance(img, Image.Image):
        return np.array(img.convert("RGB"))
    # path-like
    loaded = _load_image(img)
    if loaded is None:
        raise ValueError(f"could not read image: {img!r}")
    return np.array(loaded)


# --- localizer-based signal ------------------------------------------------

# The localizer's own is_trusted() threshold (confidence >= 0.12) is tuned
# for a much weaker claim than ours: "trustworthy enough to additionally
# protect pixels during erasure" (a false positive there just over-protects
# a few pixels). Using it as-is to decide "this page has a watermark, drop
# it" is far too eager. Empirically, no threshold cleanly separates our
# synthetic pages from the real watermarked set (real-page confidences
# start at 0.62; plenty of synthetic pages also reach 0.60-1.00, mostly the
# ones with bold rule lines/borders/dense tables) -- 0.60 was chosen as the
# highest threshold that still keeps every real page above it, which cuts
# the synthetic false-positive rate roughly 3x versus the module's own
# default (0.12) without losing any real-page recall.
_LOCALIZER_CONFIDENCE_THRESHOLD = 0.60


def _localizer_signal(gray: np.ndarray) -> tuple[bool, float, float]:
    from watermark_remover.localizer import localize_watermark, MIN_COVERAGE, MAX_COVERAGE

    _, coverage, confidence = localize_watermark(gray)
    fired = (
        confidence >= _LOCALIZER_CONFIDENCE_THRESHOLD
        and MIN_COVERAGE <= coverage <= MAX_COVERAGE
    )
    return fired, coverage, confidence


# --- segmenter-based signal (YOLO + SAM refine + false-positive classify) --

_SEGMENTER_CONF = 0.15  # matches segmenter.detect_watermark_masks's own default


def _segmenter_signal(rgb: np.ndarray, conf: float = _SEGMENTER_CONF, use_sam: bool = True) -> tuple[bool, int, int, float]:
    """Runs the project's full detection pipeline (YOLO union -> SAM refine
    -> opaque-ink/chrome false-positive classifier) and reports whether any
    instance survived the classifier. Returns (fired, accepted_count,
    rejected_count, coverage). Never raises: if the model weights,
    ultralytics/torch, or the SAM checkpoint aren't available, returns
    (False, 0, 0, 0.0) so callers degrade to the localizer-only signal
    rather than crashing the whole screening pass.

    use_sam=True (the default) is what actually makes this precise -- see
    the module docstring. Without SAM this would just be raw YOLO boxes,
    which were measured to flag 40/40 of our own clean pages; don't disable
    it unless you also raise your own tolerance for false positives.
    """
    try:
        from watermark_remover.segmenter import detect_watermark_masks
    except Exception:
        return False, 0, 0, 0.0
    try:
        _, meta = detect_watermark_masks(rgb, conf=conf, model_choice="Both (Union)", use_sam=use_sam)
    except Exception:
        return False, 0, 0, 0.0
    return meta["accepted_count"] > 0, meta["accepted_count"], meta["rejected_count"], meta["coverage"]


def looks_watermarked(img: ImageLike, use_segmenter: bool = True, use_sam: bool = True, details: bool = False):
    """Screens a background page for a pre-existing watermark.

    Parameters
    ----------
    img : path, PIL.Image, or HxWx3/HxWx4 numpy array (any of the usual
        color conventions -- normalized to RGB internally).
    use_segmenter : run the project's full YOLO+SAM+classify pipeline as
        the primary signal, in addition to the fast morphological
        localizer. Set False to skip loading ultralytics/torch/SAM
        entirely (much faster, localizer-only, meaningfully lower recall
        -- see module docstring).
    use_sam : passed through to the segmenter signal. Only matters when
        use_segmenter=True. Leave True; see _segmenter_signal's docstring
        for why disabling it reintroduces a huge false-positive rate.
    details : if True, returns a dict with the raw per-signal evidence
        instead of a plain bool -- useful for tuning/reporting.

    Returns
    -------
    bool (or dict if details=True): True if either signal found evidence of
    a pre-existing watermark. See the module docstring for this detector's
    honest, MEASURED limitations before treating True/False as ground
    truth -- in particular, it over-fires on this project's own dense
    tabular/spreadsheet synthetic pages and should not be used as an
    automatic gate on that generator's own output.
    """
    rgb = _to_rgb_array(img)
    import cv2

    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)

    loc_fired, coverage, confidence = _localizer_signal(gray)
    seg_fired, accepted, rejected, seg_coverage = (False, 0, 0, 0.0)
    if use_segmenter:
        seg_fired, accepted, rejected, seg_coverage = _segmenter_signal(rgb, use_sam=use_sam)

    verdict = bool(loc_fired or seg_fired)
    if details:
        return {
            "watermarked": verdict,
            "localizer_fired": loc_fired,
            "localizer_coverage": coverage,
            "localizer_confidence": confidence,
            "segmenter_fired": seg_fired,
            "segmenter_accepted": accepted,
            "segmenter_rejected": rejected,
            "segmenter_coverage": seg_coverage,
        }
    return verdict
